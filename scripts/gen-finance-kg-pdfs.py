S = styles()


def P(text, style="body"):
    return Paragraph(text, S[style])


def bullets(items):
    return ListFlowable(
        [ListItem(P(i), leftIndent=12, bulletColor=NAVY) for i in items],
        bulletType="bullet",
        start="•",
        leftIndent=16,
        bulletFontName="Hei",
        bulletFontSize=9,
        spaceAfter=8,
    )


def table(headers, rows, col_widths=None, caption=None):
    head = [P(h, "th") for h in headers]
    body = []
    for r in rows:
        body.append([P(str(c), "cell_c" if i == 0 else "cell") for i, c in enumerate(r)])
    data = [head] + body
    t = Table(data, colWidths=col_widths, repeatRows=1)
    cmds = [
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("TEXTCOLOR", (0, 0), (-1, 0), white),
        ("FONTNAME", (0, 0), (-1, 0), "HeiBold"),
        ("ALIGN", (0, 0), (-1, 0), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("GRID", (0, 0), (-1, -1), 0.4, LINE),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("RIGHTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("BACKGROUND", (0, 1), (-1, -1), white),
    ]
    for i in range(1, len(data)):
        if i % 2 == 0:
            cmds.append(("BACKGROUND", (0, i), (-1, i), ROW_ALT))
    t.setStyle(TableStyle(cmds))
    flow = [t]
    if caption:
        flow.append(P(caption, "caption"))
    else:
        flow.append(Spacer(1, 8))
    return flow


def meta_block(pairs):
    data = [[P(f"<b>{k}</b>", "meta"), P(v, "meta")] for k, v in pairs]
    t = Table(data, colWidths=[38 * mm, 132 * mm])
    t.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                ("TOPPADDING", (0, 0), (-1, -1), 1),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
            ]
        )
    )
    return t


def hr():
    return HRFlowable(width="100%", thickness=1.2, color=NAVY, spaceBefore=4, spaceAfter=8)


def make_header_footer(doc_no, title):
    def _draw(canvas, doc):
        canvas.saveState()
        w, h = A4
        canvas.setFillColor(NAVY)
        canvas.rect(0, h - 16 * mm, w, 16 * mm, fill=1, stroke=0)
        canvas.setFillColor(GOLD)
        canvas.rect(0, h - 16.8 * mm, w, 1.2 * mm, fill=1, stroke=0)
        canvas.setFillColor(white)
        canvas.setFont("Hei", 8)
        canvas.drawString(18 * mm, h - 8.5 * mm, COMPANY)
        canvas.drawRightString(w - 18 * mm, h - 8.5 * mm, "内部资料 · 财务知识库")
        canvas.setFillColor(LINE)
        canvas.rect(0, 12 * mm, w, 0.4, fill=1, stroke=0)
        canvas.setFillColor(MUTED)
        canvas.setFont("Hei", 8)
        canvas.drawString(18 * mm, 7 * mm, f"{doc_no}　{title}")
        canvas.drawRightString(w - 18 * mm, 7 * mm, f"第 {doc.page} 页")
        canvas.restoreState()

    return _draw


def cover(doc_no, title, subtitle, extra_pairs):
    flow = [
        P("机密等级：内部公开", "secret"),
        Spacer(1, 8),
        P(COMPANY, "cover_co"),
        P("财务中心 · 知识管理", "cover_co"),
        Spacer(1, 10),
        hr(),
        P(title, "cover_title"),
        hr(),
        P(subtitle, "cover_sub"),
        Spacer(1, 12),
        meta_block([("文档编号", doc_no), *extra_pairs]),
        Spacer(1, 8),
        P(
            "本文档与同知识库内其他财务制度、项目预算、供应商清单相互引用。"
            "抽取实体时请保持名称原文：部门（财务部、采购部、研发中心、审计部、项目管理办公室）；"
            "人员（陈思远、林婉清、赵启明、周嘉宁、吴振华、孙雨桐、郑浩然、黄晓薇、钱志远、何嘉慧）；"
            "项目（星云ERP升级项目、智能工厂一期项目、海外供应链数字化项目、2025年度全面预算编制项目、应收账款专项清收项目）；"
            "供应商（华云科技、天枢软件、金桥融资租赁、远航物流、锐智咨询、鼎信会计师事务所）；"
            "制度（差旅报销管理办法、供应商付款审批制度、项目预算与成本核算办法、关联交易披露指引、内部控制评价办法）。",
            "meta",
        ),
    ]
    return flow


def build_pdf(filename, doc_no, title, flowables):
    os.makedirs(OUT_DIR, exist_ok=True)
    path = os.path.join(OUT_DIR, filename)
    doc = SimpleDocTemplate(
        path,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=22 * mm,
        bottomMargin=18 * mm,
        title=title,
        author=COMPANY,
        subject=doc_no,
    )
    doc.build(flowables, onFirstPage=make_header_footer(doc_no, title), onLaterPages=make_header_footer(doc_no, title))
    size = os.path.getsize(path)
    print(f"{filename:48s}  {size/1024:7.1f} KB")
    return path


